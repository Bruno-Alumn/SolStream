import AppKit
import XCTest
@testable import SolStreamClient

/// What the clipboard bridge lets cross between the Mac and the PC.
final class ClipboardSyncTests: XCTestCase {

    private func types(_ names: String...) -> [NSPasteboard.PasteboardType] {
        names.map { NSPasteboard.PasteboardType($0) }
    }

    // MARK: - What stays on the Mac

    func testAnOrdinaryCopyCrosses() {
        XCTAssertFalse(ClipboardBridge.isPrivate(types: [.string]))
        XCTAssertFalse(ClipboardBridge.isPrivate(types: [.string, .rtf, .html]))
        XCTAssertFalse(ClipboardBridge.isPrivate(types: nil), "an empty pasteboard")
    }

    /// The nspasteboard.org markers a password manager sets beside what it
    /// copies. Any one of them keeps the copy on this Mac.
    func testEachMarkerKeepsTheCopyHere() {
        for marker in ["org.nspasteboard.ConcealedType",
                       "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(ClipboardBridge.isPrivate(types: [.string] + types(marker)), marker)
        }
    }

    /// A marker is matched by its exact name, not by looking similar.
    func testOnlyTheExactMarkerCounts() {
        XCTAssertFalse(ClipboardBridge.isPrivate(
            types: [.string] + types("org.nspasteboard.concealedtype", "com.example.Concealed")))
    }

    /// `NSPasteboard.types` is the union over every item, so a marker on the
    /// second of two items still shows up. Checked on a pasteboard of its own,
    /// never the general one the person is using.
    func testAMarkerOnAnyItemKeepsTheWholeCopyHere() {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("SolStream.tests.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        let plain = NSPasteboardItem()
        plain.setString("username", forType: .string)
        let secret = NSPasteboardItem()
        secret.setString("password", forType: .string)
        secret.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        XCTAssertTrue(pasteboard.writeObjects([plain, secret]))
        XCTAssertTrue(ClipboardBridge.isPrivate(types: pasteboard.types))
    }
}
