import AppKit
import XCTest
@testable import SolStreamClient

/// What the clipboard bridge lets cross between the Mac and the PC.
final class ClipboardSyncTests: XCTestCase {

    private func types(_ names: String...) -> [NSPasteboard.PasteboardType] {
        names.map { NSPasteboard.PasteboardType($0) }
    }

    // MARK: - What stays on the Mac

    func testAnOrdinaryCopyCrosses() {
        XCTAssertFalse(ClipboardBridge.isPrivate(types: [.string]))
        XCTAssertFalse(ClipboardBridge.isPrivate(types: [.string, .rtf, .html]))
        XCTAssertFalse(ClipboardBridge.isPrivate(types: nil), "an empty pasteboard")
    }

    /// The nspasteboard.org markers a password manager sets beside what it
    /// copies, and the older names it lists, which some applications still
    /// set instead. Any one of them keeps the copy on this Mac.
    func testEachMarkerKeepsTheCopyHere() {
        for marker in ["org.nspasteboard.ConcealedType",
                       "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType",
                       "com.agilebits.onepassword",
                       "de.petermaurer.TransientPasteboardType",
                       "com.typeit4me.clipping",
                       "Pasteboard generator type"] {
            XCTAssertTrue(ClipboardBridge.isPrivate(types: [.string] + types(marker)), marker)
        }
    }

    /// A marker is matched by its exact name, not by looking similar.
    func testOnlyTheExactMarkerCounts() {
        XCTAssertFalse(ClipboardBridge.isPrivate(
            types: [.string] + types("org.nspasteboard.concealedtype", "com.example.Concealed")))
    }

    /// `NSPasteboard.types` is the union over every item, so a marker on the
    /// second of two items still shows up. Checked on a pasteboard of its own,
    /// never the general one the person is using.
    func testAMarkerOnAnyItemKeepsTheWholeCopyHere() {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("SolStream.tests.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        let plain = NSPasteboardItem()
        plain.setString("username", forType: .string)
        let secret = NSPasteboardItem()
        secret.setString("password", forType: .string)
        secret.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        XCTAssertTrue(pasteboard.writeObjects([plain, secret]))
        XCTAssertTrue(ClipboardBridge.isPrivate(types: pasteboard.types))
    }

    // MARK: - Line endings

    func testTheMacsLinesBecomeWindowsLines() {
        XCTAssertEqual(ClipboardBridge.windowsLineEndings("one\ntwo\n"), "one\r\ntwo\r\n")
        XCTAssertEqual(ClipboardBridge.windowsLineEndings("\n\n"), "\r\n\r\n")
        XCTAssertEqual(ClipboardBridge.windowsLineEndings("no line break"), "no line break")
    }

    func testWindowsLinesBecomeTheMacs() {
        XCTAssertEqual(ClipboardBridge.macLineEndings("one\r\ntwo\r\n"), "one\ntwo\n")
        XCTAssertEqual(ClipboardBridge.macLineEndings("\r\n\r\n"), "\n\n")
        XCTAssertEqual(ClipboardBridge.macLineEndings("one\ntwo"), "one\ntwo")
    }

    /// Both ends convert, so either may meet text the other has already
    /// converted: doing it twice must be doing it once.
    func testConvertingTwiceChangesNothingMore() {
        let mixed = "a\nb\r\nc"
        let once = ClipboardBridge.windowsLineEndings(mixed)
        XCTAssertEqual(once, "a\r\nb\r\nc")
        XCTAssertEqual(ClipboardBridge.windowsLineEndings(once), once)
        let folded = ClipboardBridge.macLineEndings(mixed)
        XCTAssertEqual(folded, "a\nb\nc")
        XCTAssertEqual(ClipboardBridge.macLineEndings(folded), folded)
    }

    /// A CR on its own is not a Windows line ending, and is left where it is.
    func testALoneReturnIsLeftAlone() {
        XCTAssertEqual(ClipboardBridge.windowsLineEndings("a\rb"), "a\rb")
        XCTAssertEqual(ClipboardBridge.macLineEndings("a\rb"), "a\rb")
        XCTAssertEqual(ClipboardBridge.macLineEndings("ends in a CR\r"), "ends in a CR\r")
        XCTAssertEqual(ClipboardBridge.macLineEndings("a\r\rb"), "a\r\rb")
    }

    /// A run of CRs before an LF — an edit control's soft line break, or a
    /// CRLF converted twice — is one line ending, and folds to one LF. So
    /// nothing folded holds a CRLF, and folding it again changes nothing: the
    /// host folds before it sends, and this Mac and one that does not fold
    /// get the same text.
    func testARunOfReturnsBeforeALineFeedIsOneLineEnding() {
        XCTAssertEqual(ClipboardBridge.macLineEndings("\r\r\n"), "\n")
        XCTAssertEqual(ClipboardBridge.macLineEndings("a\r\r\nb\r\r\r\nc"), "a\nb\nc")
        for text in ["a\r\r\nb", "\r\r\r\n", "a\r\n\r\nb\r", "\r\ra\r\r", "one\r\ntwo\n\rthree"] {
            let once = ClipboardBridge.macLineEndings(text)
            XCTAssertEqual(ClipboardBridge.macLineEndings(once), once, text.debugDescription)
            let scalars = Array(once.unicodeScalars)
            XCTAssertFalse(zip(scalars, scalars.dropFirst()).contains { $0 == "\r" && $1 == "\n" },
                           text.debugDescription)
        }
    }

    /// Swift counts CRLF as one Character, so a conversion that searched by
    /// Character would never see the LF inside it, and one that cut by
    /// Character could not separate the two.
    func testCRLFIsTwoScalarsToTheConversion() {
        XCTAssertEqual("\r\n".count, 1)
        XCTAssertEqual(ClipboardBridge.macLineEndings("x\r\ny").unicodeScalars.count, 3)
        XCTAssertEqual(ClipboardBridge.windowsLineEndings("x\ny").unicodeScalars.count, 4)
    }

    func testThereAndBackIsTheMacsTextAsItWas() {
        let text = "first line\nsecond, with a tab\there\n\nafter a blank line"
        XCTAssertEqual(ClipboardBridge.macLineEndings(ClipboardBridge.windowsLineEndings(text)), text)
    }

    func testTextBeyondASCIIPassesThrough() {
        let text = "café\n漢字\n🇪🇸 and 👩‍👩‍👧"
        let windows = ClipboardBridge.windowsLineEndings(text)
        XCTAssertEqual(windows, "café\r\n漢字\r\n🇪🇸 and 👩‍👩‍👧")
        XCTAssertEqual(ClipboardBridge.macLineEndings(windows), text)
    }

    func testEmptyStaysEmpty() {
        XCTAssertEqual(ClipboardBridge.windowsLineEndings(""), "")
        XCTAssertEqual(ClipboardBridge.macLineEndings(""), "")
    }
}
